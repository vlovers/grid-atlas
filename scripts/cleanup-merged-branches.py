#!/usr/bin/env python3
"""Audit remote GitHub branches and optionally delete strictly verified merged refs.

Requires authenticated gh CLI. No deletes without --apply, --confirm and a
manifest generated by an earlier audit. Uses only stdlib; no CI triggered.
"""
import argparse
import json
import subprocess
import sys
from pathlib import Path
from urllib.parse import quote

def api(path, method="GET"):
    cmd = ["gh", "api", "-H", "Accept: application/vnd.github+json"]
    if method != "GET":
        cmd += ["-X", method]
    cmd.append(path)
    result = subprocess.run(cmd, check=True, text=True, capture_output=True)
    return json.loads(result.stdout) if result.stdout.strip() else {}

def paged(repo, resource):
    data = []
    page = 1
    while True:
        part = api(f"repos/{repo}/{resource}{'&' if '?' in resource else '?'}per_page=100&page={page}")
        if not isinstance(part, list):
            raise RuntimeError(f"Unexpected GitHub response for {resource}: expected list")
        data.extend(part)
        if len(part) < 100:
            return data
        page += 1

def validate_repo(value):
    chunks = value.split("/")
    if len(chunks) != 2 or any(not c or not all(ch.isalnum() or ch in "._-" for ch in c) for c in chunks):
        raise ValueError("Repository must be owner/repo")
    return value

def ref_info(repo, name):
    encoded = quote(name, safe="/")
    return api(f"repos/{repo}/branches/{encoded}")

def compare(repo, base, sha):
    return api(f"repos/{repo}/compare/{quote(base, safe='')}...{sha}")

def list_referenced_branches(repo):
    """Protect both the head AND base of every open PR in this repository."""
    referenced = set()
    for pr in paged(repo, "pulls?state=open"):
        head = pr.get("head") or {}
        base = pr.get("base") or {}
        if (head.get("repo") or {}).get("full_name") == repo and head.get("ref"):
            referenced.add(head["ref"])
        if (base.get("repo") or {}).get("full_name") == repo and base.get("ref"):
            referenced.add(base["ref"])
    return referenced

def audit(repo, selected=None):
    repository = api(f"repos/{repo}")
    base = repository["default_branch"]
    base_sha = ref_info(repo, base)["commit"]["sha"]
    heads = list_referenced_branches(repo)
    entries = []
    for branch in paged(repo, "branches"):
        name, sha = branch["name"], branch["commit"]["sha"]
        if selected is not None and name not in selected:
            continue
        reason = "pr_head_or_base" if name in heads else "default" if name == base else "protected" if branch.get("protected") else None
        entry = {"name": name, "sha": sha, "protected": bool(branch.get("protected"))}
        if reason:
            entry.update(status="retain", reason=reason)
        else:
            result = compare(repo, base, sha)
            entry.update(status="candidate" if result.get("ahead_by") == 0 and result.get("status") in ("behind", "identical") else "retain",
                         reason=result.get("status", "unknown"),
                         ahead_by=result.get("ahead_by"), behind_by=result.get("behind_by"))
        entries.append(entry)
    if ref_info(repo, base)["commit"]["sha"] != base_sha:
        raise RuntimeError("Default branch moved during inventory; discard the manifest and rerun")
    return {"repository": repo, "base": base, "base_sha": base_sha, "entries": entries}

def apply(manifest, max_delete=10):
    repo = validate_repo(manifest["repository"])
    current = api(f"repos/{repo}")
    if manifest["base"] != current["default_branch"]:
        raise RuntimeError("Default branch changed; stop.")
    if ref_info(repo, current["default_branch"])["commit"]["sha"] != manifest.get("base_sha"):
        raise RuntimeError("Default branch SHA changed since inventory; regenerate and review the manifest")
    open_heads = list_referenced_branches(repo)
    candidates = [row for row in manifest["entries"] if row.get("status") == "candidate"]
    if len(candidates) > max_delete:
        raise RuntimeError(f"{len(candidates)} deletions exceed --max-delete={max_delete}; review a smaller manifest")
    if len({row["name"] for row in candidates}) != len(candidates):
        raise RuntimeError("Duplicate candidate names in manifest")
    deleted, skipped = [], []
    for row in manifest["entries"]:
        if row.get("status") != "candidate":
            continue
        name, expected = row["name"], row["sha"]
        if name == current["default_branch"] or name in open_heads:
            skipped.append([name, "protected by default/open PR"])
            continue
        try:
            actual = ref_info(repo, name)
        except subprocess.CalledProcessError:
            skipped.append([name, "branch missing or inaccessible"])
            continue
        if actual.get("protected") or actual["commit"]["sha"] != expected:
            skipped.append([name, "protected or branch SHA changed"])
            continue
        result = compare(repo, current["default_branch"], expected)
        if result.get("ahead_by") != 0 or result.get("status") not in ("behind", "identical"):
            skipped.append([name, "not confirmed ancestor"])
            continue
        # REST DELETE has no conditional ref lease; immediately re-check SHA.
        if ref_info(repo, name)["commit"]["sha"] != expected:
            skipped.append([name, "branch moved on final check"])
            continue
        if ref_info(repo, current["default_branch"])["commit"]["sha"] != manifest["base_sha"]:
            raise RuntimeError("Default branch changed during cleanup; stop before further deletion")
        api(f"repos/{repo}/git/refs/heads/{quote(name, safe='/')}", method="DELETE")
        deleted.append({"name": name, "sha": expected})
    return {"deleted": deleted, "skipped": skipped}

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--repo", default="vlovers/grid-atlas")
    parser.add_argument("--manifest", type=Path, default=Path("/tmp/grid-atlas-branch-cleanup-manifest.json"))
    parser.add_argument("--apply", action="store_true")
    parser.add_argument("--confirm", default="")
    parser.add_argument("--max-delete", type=int, default=10, help="Hard cap per apply invocation (default 10)")
    parser.add_argument("--only", action="append", help="Inspect one name; repeat as needed")
    args = parser.parse_args()
    repo = validate_repo(args.repo)
    if args.apply:
        if args.confirm != "DELETE-VERIFIED-ANCESTORS":
            parser.error("--apply requires --confirm DELETE-VERIFIED-ANCESTORS")
        if not args.manifest.exists():
            parser.error("An existing, reviewed manifest is required for deletion")
        manifest = json.loads(args.manifest.read_text())
        if manifest["repository"] != repo:
            parser.error("Manifest repository mismatch")
        if args.max_delete < 1 or args.max_delete > 20:
            parser.error("--max-delete must be between 1 and 20")
        report = apply(manifest, max_delete=args.max_delete)
        print(json.dumps(report, ensure_ascii=False, indent=2))
    else:
        report = audit(repo, set(args.only) if args.only else None)
        args.manifest.write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n")
        counts = {}
        for row in report["entries"]:
            key = row["status"]
            counts[key] = counts.get(key, 0) + 1
        print(json.dumps({"manifest": str(args.manifest), "count": len(report["entries"]), "by_status": counts}, indent=2))

if __name__ == "__main__":
    try:
        main()
    except (OSError, ValueError, KeyError, RuntimeError, subprocess.CalledProcessError) as exc:
        print(f"Branch cleanup stopped: {exc}", file=sys.stderr)
        raise SystemExit(1)
